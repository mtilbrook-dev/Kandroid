package dev.tilbrook.kandroid.typedmanifest.internal.generate

import dev.tilbrook.kandroid.typedmanifest.internal.model.ManifestElement
import dev.tilbrook.kandroid.typedmanifest.internal.model.Specs
import dev.tilbrook.kandroid.typedmanifest.internal.model.TypedManifestException
import dev.tilbrook.kandroid.typedmanifest.internal.source.SourceParser
import dev.tilbrook.kandroid.typedmanifest.internal.source.SourceSyntaxException

/**
 * A source file to scan. [path] is used in error messages (absolute, so IDEs can link it);
 * [displayPath] is recorded in the generated manifest and its source map (project-relative, so
 * cached outputs are portable).
 */
internal data class SourceInput(val path: String, val text: String, val displayPath: String = path)

/** A position in a source file, as recorded in the generated manifest's source map. */
internal data class SourceLocation(val path: String, val line: Int)

/** Rendered manifest text plus, for each generated line (1-based), the source it came from. */
internal class RenderedManifest(val text: String, val sourceLines: Map<Int, SourceLocation>)

/** Which entry kinds the generator should collect. Activities only for now. */
internal data class GeneratorOptions(val activities: Boolean = true)

internal object ManifestGenerator {

    /** Scans [sources] and returns the generated `<activity>` (etc.) elements, sorted by name. */
    fun collect(sources: Sequence<SourceInput>, options: GeneratorOptions = GeneratorOptions()): List<ManifestElement> {
        val problems = ArrayList<String>()
        val elements = ArrayList<ManifestElement>()
        val target = Specs.activity.fqName
        for (input in sources) {
            // Cheap pre-filter: skip files that can't mention the annotation.
            if (!options.activities || !input.text.contains("Activity")) continue
            if (!input.text.contains("Manifest")) continue
            try {
                val parsed = SourceParser.parse(input.path, input.text)
                for (annotated in parsed.annotatedClasses(target)) {
                    val (element, errors) = AnnotationConverter(parsed, input.displayPath).convertActivity(annotated)
                    problems += errors
                    if (element != null) elements += element
                }
            } catch (e: SourceSyntaxException) {
                problems += "${input.path}:${e.line}: ${e.message}"
            }
        }
        elements.groupBy { it.attr("name") }.filterValues { it.size > 1 }.keys.forEach {
            problems += "Activity $it is declared more than once"
        }
        if (problems.isNotEmpty()) throw TypedManifestException(problems)
        return elements.sortedBy { it.attr("name") }
    }

    /** Marker on the second line of every generated manifest; lint uses it to recognise the file. */
    const val GENERATED_MARKER = "Generated by dev.tilbrook.typed-manifest"

    private const val TOOLS_NS = "http://schemas.android.com/tools"

    /**
     * Built-in lint checks that typed-manifest re-implements on `@Manifest.Activity` itself (so they
     * point at source). The generated entries opt out of the built-in versions via `tools:ignore`.
     */
    val REPLACED_LINT_CHECKS = listOf("AppLinkUrlError", "Instantiatable", "DiscouragedApi", "LockedOrientationActivity")

    fun render(entries: List<ManifestElement>): String = renderWithSourceMap(entries).text

    fun renderWithSourceMap(
        entries: List<ManifestElement>,
        toolsIgnore: List<String> = REPLACED_LINT_CHECKS,
    ): RenderedManifest {
        val w = Writer()
        w.line("<?xml version=\"1.0\" encoding=\"utf-8\"?>")
        w.line("<!-- $GENERATED_MARKER from @Manifest annotations. Do not edit. -->")
        val toolsNs = if (toolsIgnore.isNotEmpty()) " xmlns:tools=\"$TOOLS_NS\"" else ""
        w.line("<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\"$toolsNs>")
        if (entries.isEmpty()) {
            w.line("    <application />")
        } else {
            w.line("    <application>")
            val ignore = toolsIgnore.takeIf { it.isNotEmpty() }?.joinToString(",")
            entries.forEach { w.element(it, 2, ignore) }
            w.line("    </application>")
        }
        w.line("</manifest>")
        return RenderedManifest(w.text, w.sourceLines)
    }

    /** Just the entry elements, indented for placement inside an existing `<application>`. */
    fun renderEntries(entries: List<ManifestElement>, depth: Int): String {
        val w = Writer()
        entries.forEach { w.element(it, depth, toolsIgnore = null) }
        return w.text
    }

    private class Writer {
        private val sb = StringBuilder()
        private var next = 1
        val sourceLines = LinkedHashMap<Int, SourceLocation>()
        val text: String get() = sb.toString()

        fun line(text: String, source: SourceLocation? = null) {
            if (source != null) sourceLines[next] = source
            sb.append(text).append('\n')
            next++
        }

        fun element(element: ManifestElement, depth: Int, toolsIgnore: String?) {
            val indent = "    ".repeat(depth)
            val src = element.source
            val here = src?.let { SourceLocation(it.path, it.line) }
            fun at(attribute: String) = src?.let { SourceLocation(it.path, it.lineFor(attribute)) }

            if (element.tag == "activity" && src != null) {
                val simple = element.attr("name")?.substringAfterLast('.')?.substringAfterLast('$') ?: "activity"
                line("$indent<!-- $simple: ${src.path}:${src.line} -->", here)
            }

            val attrs = element.attributes.map { (k, v) -> Triple("android:$k", escape(v), at(k)) } +
                listOfNotNull(toolsIgnore?.takeIf { element.tag == "activity" }?.let { Triple("tools:ignore", it, here) })
            val close = if (element.children.isEmpty()) " />" else ">"

            if (attrs.size <= 1) {
                val a = attrs.singleOrNull()?.let { (k, v, _) -> " $k=\"$v\"" }.orEmpty()
                line("$indent<${element.tag}$a$close", here)
            } else {
                line("$indent<${element.tag}", here)
                attrs.forEachIndexed { i, (k, v, loc) ->
                    line("$indent    $k=\"$v\"" + if (i == attrs.lastIndex) close else "", loc ?: here)
                }
            }
            if (element.children.isNotEmpty()) {
                element.children.forEach { element(it, depth + 1, toolsIgnore = null) }
                line("$indent</${element.tag}>", here)
            }
        }
    }

    private fun escape(value: String) = buildString {
        value.forEach {
            when (it) {
                '&' -> append("&amp;")
                '<' -> append("&lt;")
                '>' -> append("&gt;")
                '"' -> append("&quot;")
                '\n' -> append("&#10;")
                '\t' -> append("&#9;")
                else -> append(it)
            }
        }
    }
}
