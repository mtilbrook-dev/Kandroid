package dev.tilbrook.kandroid.typedmanifest

import dev.tilbrook.kandroid.typedmanifest.internal.generate.ManifestGenerator
import dev.tilbrook.kandroid.typedmanifest.internal.generate.SourceInput
import dev.tilbrook.kandroid.typedmanifest.internal.model.TypedManifestException
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class ManifestGeneratorTest {

    private fun generate(vararg files: Pair<String, String>): String =
        ManifestGenerator.render(ManifestGenerator.collect(files.map { SourceInput(it.first, it.second) }.asSequence()))

    private fun failure(vararg files: Pair<String, String>): String =
        assertThrows(TypedManifestException::class.java) { generate(*files) }.message!!

    @Test
    fun `bare annotation is secure by default`() {
        val xml = generate(
            "Detail.kt" to """
                package com.example

                import dev.tilbrook.kandroid.typedmanifest.Manifest

                @Manifest.Activity
                class DetailActivity : Activity()
            """.trimIndent(),
        )
        assertEquals(
            """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by dev.tilbrook.typed-manifest from @Manifest annotations. Do not edit. -->
            <manifest xmlns:android="http://schemas.android.com/apk/res/android">
                <application>
                    <activity
                        android:name="com.example.DetailActivity"
                        android:exported="false" />
                </application>
            </manifest>

            """.trimIndent(),
            xml,
        )
    }

    @Test
    fun `no annotations produces an empty application`() {
        val xml = generate("A.kt" to "package a\nclass A")
        assertTrue(xml.contains("<application />"), xml)
    }

    @Test
    fun `all value kinds are written`() {
        val xml = generate(
            "Main.kt" to """
                package com.example.app

                import dev.tilbrook.kandroid.typedmanifest.Manifest
                import com.example.app.home.HomeActivity

                /** Docs mentioning @Manifest.Activity(exported = "nope") are ignored. */
                @Suppress("unused")
                @Manifest.Activity(
                    exported = true,
                    label = "@string/app" + "_name",
                    theme = "@style/Theme.App",
                    launchMode = Manifest.LaunchMode.SINGLE_TOP,
                    configChanges = [Manifest.ConfigChange.ORIENTATION, Manifest.ConfigChange.SCREEN_SIZE],
                    windowSoftInputMode = [Manifest.WindowSoftInputMode.ADJUST_RESIZE],
                    maxAspectRatio = 2.4f,
                    maxRecents = 0x10,
                    parentActivity = HomeActivity::class,
                    intentFilters = [
                        Manifest.IntentFilter(
                            actions = [Manifest.Action.MAIN],
                            categories = [Manifest.Category.LAUNCHER],
                        ),
                        Manifest.IntentFilter(
                            actions = ["android.intent.action.VIEW"],
                            categories = [Manifest.Category.DEFAULT, Manifest.Category.BROWSABLE],
                            data = [Manifest.Data(scheme = "https", host = "example.com", pathPrefix = "/a")],
                            autoVerify = true,
                        ),
                    ],
                    metaData = [Manifest.MetaData(name = "k", value = "v")],
                    layout = Manifest.Layout(defaultWidth = "600dp", gravity = "top|end"),
                )
                open class MainActivity : Activity() {
                    val s = "@Manifest.Activity"
                }
            """.trimIndent(),
        )
        val expected = """
            |        <activity
            |            android:name="com.example.app.MainActivity"
            |            android:exported="true"
            |            android:label="@string/app_name"
            |            android:theme="@style/Theme.App"
            |            android:launchMode="singleTop"
            |            android:configChanges="orientation|screenSize"
            |            android:windowSoftInputMode="adjustResize"
            |            android:maxAspectRatio="2.4"
            |            android:maxRecents="16"
            |            android:parentActivityName="com.example.app.home.HomeActivity">
            |            <intent-filter>
            |                <action android:name="android.intent.action.MAIN" />
            |                <category android:name="android.intent.category.LAUNCHER" />
            |            </intent-filter>
            |            <intent-filter android:autoVerify="true">
            |                <action android:name="android.intent.action.VIEW" />
            |                <category android:name="android.intent.category.DEFAULT" />
            |                <category android:name="android.intent.category.BROWSABLE" />
            |                <data
            |                    android:scheme="https"
            |                    android:host="example.com"
            |                    android:pathPrefix="/a" />
            |            </intent-filter>
            |            <meta-data
            |                android:name="k"
            |                android:value="v" />
            |            <layout
            |                android:defaultWidth="600dp"
            |                android:gravity="top|end" />
            |        </activity>
        """.trimMargin()
        assertTrue(xml.contains(expected), xml)
    }

    @Test
    fun `java sources are supported`() {
        val xml = generate(
            "com/example/JavaActivity.java" to """
                package com.example;

                import dev.tilbrook.kandroid.typedmanifest.Manifest;

                @Manifest.Activity(
                    exported = true,
                    screenOrientation = Manifest.ScreenOrientation.PORTRAIT,
                    parentActivity = MainActivity.class,
                    intentFilters = @Manifest.IntentFilter(actions = {Manifest.Action.MAIN}, categories = Manifest.Category.LAUNCHER)
                )
                public final class JavaActivity extends Activity {
                    private final String s = "class Foo {";
                }
            """.trimIndent(),
        )
        assertTrue(xml.contains("android:name=\"com.example.JavaActivity\""), xml)
        assertTrue(xml.contains("android:screenOrientation=\"portrait\""), xml)
        assertTrue(xml.contains("android:parentActivityName=\"com.example.MainActivity\""), xml)
        assertTrue(xml.contains("<category android:name=\"android.intent.category.LAUNCHER\" />"), xml)
    }

    @Test
    fun `nested classes use binary names`() {
        val xml = generate(
            "Outer.kt" to """
                package com.example
                import dev.tilbrook.kandroid.typedmanifest.Manifest
                class Outer(val f: () -> Unit = { }) {
                    fun helper() { val x = object : Runnable { override fun run() {} } }
                    @Manifest.Activity
                    class Inner : Activity()
                }
                @Manifest.Activity class Top : Activity()
            """.trimIndent(),
        )
        assertTrue(xml.contains("android:name=\"com.example.Outer\$Inner\""), xml)
        assertTrue(xml.contains("android:name=\"com.example.Top\""), xml)
    }

    @Test
    fun `import forms resolve and lookalike annotations are ignored`() {
        val xml = generate(
            "a/A.kt" to """
                package a
                import dev.tilbrook.kandroid.typedmanifest.Manifest.Activity as Screen
                @Screen class A : android.app.Activity()
            """.trimIndent(),
            "b/B.kt" to """
                package b
                import dev.tilbrook.kandroid.typedmanifest.Manifest.*
                @Activity(exported = false) class B
            """.trimIndent(),
            "c/C.kt" to """
                package c
                @dev.tilbrook.kandroid.typedmanifest.Manifest.Activity class C
            """.trimIndent(),
            "d/D.kt" to """
                package d
                import other.Manifest
                @Manifest.Activity class D
            """.trimIndent(),
        )
        assertTrue(xml.contains("\"a.A\""), xml)
        assertTrue(xml.contains("\"b.B\""), xml)
        assertTrue(xml.contains("\"c.C\""), xml)
        assertTrue(!xml.contains("\"d.D\""), xml)
    }

    @Test
    fun `launcher must be exported`() {
        val message = failure(
            "L.kt" to """
                package l
                import dev.tilbrook.kandroid.typedmanifest.Manifest
                @Manifest.Activity(
                    intentFilters = [Manifest.IntentFilter(actions = [Manifest.Action.MAIN], categories = [Manifest.Category.LAUNCHER])],
                )
                class L
            """.trimIndent(),
        )
        assertTrue(message.contains("L.kt:3:"), message)
        assertTrue(message.contains("exported = true"), message)
    }

    @Test
    fun `invalid arguments report file and line`() {
        val message = failure(
            "Bad.kt" to """
                package bad
                import dev.tilbrook.kandroid.typedmanifest.Manifest
                const val THEME = "@style/X"
                @Manifest.Activity(
                    lable = "x",
                    theme = THEME,
                    launchMode = Manifest.LaunchMode.NOPE,
                    exported = "true",
                )
                class Bad
            """.trimIndent(),
        )
        assertTrue(message.contains("Bad.kt:5: Unknown parameter 'lable'"), message)
        assertTrue(message.contains("Bad.kt:6: Cannot resolve 'THEME'"), message)
        assertTrue(message.contains("Bad.kt:7: Expected a Manifest.LaunchMode entry"), message)
        assertTrue(message.contains("Bad.kt:8: Expected true or false"), message)
    }

    @Test
    fun `annotation must target a class`() {
        val message = failure(
            "F.kt" to """
                package f
                import dev.tilbrook.kandroid.typedmanifest.Manifest
                @Manifest.Activity
                fun nope() = Unit
            """.trimIndent(),
        )
        assertTrue(message.contains("must be placed on a class"), message)
    }

    @Test
    fun `duplicates and string templates are rejected`() {
        val dup = failure(
            "A.kt" to "package x\nimport dev.tilbrook.kandroid.typedmanifest.Manifest\n@Manifest.Activity class A",
            "B.kt" to "package x\nimport dev.tilbrook.kandroid.typedmanifest.Manifest\n@Manifest.Activity class A",
        )
        assertTrue(dup.contains("x.A is declared more than once"), dup)

        val template = failure(
            "T.kt" to "package t\nimport dev.tilbrook.kandroid.typedmanifest.Manifest\nval n = 1\n@Manifest.Activity(label = \"\$n\") class T",
        )
        assertTrue(template.contains("String templates are not supported"), template)
    }

    @Test
    fun `values are xml escaped`() {
        val xml = generate(
            "E.kt" to """
                package e
                import dev.tilbrook.kandroid.typedmanifest.Manifest
                @Manifest.Activity(label = "Tom & \"Jerry\" <3")
                class E
            """.trimIndent(),
        )
        assertTrue(xml.contains("android:label=\"Tom &amp; &quot;Jerry&quot; &lt;3\""), xml)
    }
}
